-- Этот скрипт создаёт 6 таблиц в базе learning_db на сервере course_pg_primary
-- (порт 5432) для практики по Урокам 5.1–5.4:
--   1. replication_heartbeat — пульс кластера для проверки репликации и лага
--   2. ops_orders            — заказы (отчёты на Standby, бэкапы, логическая репликация)
--   3. billing_accounts      — счета клиентов (синхронные коммиты, PITR, PgBouncer)
--   4. catalog_sync          — каталог с колонкой себестоимости и флагом публикации (5.3)
--   5. raw_audit_events      — таблица БЕЗ Primary Key для опыта с REPLICA IDENTITY (5.3)
--   6. telemetry_stream      — 5 000 строк для генерации WAL, лага и проверки бэкапов
--
-- Благодаря физической потоковой репликации все таблицы автоматически появятся
-- и на сервере course_pg_standby (порт 5433). Сервер course_pg_logical (5434)
-- остаётся чистым — на нём ты сам создашь таблицы-приёмники в Уроке 5.3.
--
-- Скрипт идемпотентен: его можно запускать повторно в любой момент для сброса данных.
--
-- Как запустить из терминала (из корневой папки курса):
--   0. Подними профиль Модуля 5:
--      docker compose --profile mod5 up -d
--
--   Linux / macOS / Git Bash:
--      docker exec -i course_pg_primary psql -U student -d learning_db < practice/module_5/init.sql
--
--   Windows PowerShell:
--      Get-Content practice/module_5/init.sql -Raw | docker exec -i course_pg_primary psql -U student -d learning_db
--
-- Либо открой этот файл в DBeaver / DataGrip / Adminer (localhost:5432) и выполни целиком.
-- ============================================================================

-- 1. Удаляем учебные публикации (если остались от Урока 5.3) и старые таблицы
DROP PUBLICATION IF EXISTS catalog_pub, orders_pub, audit_pub, billing_pub, ddl_pub;

DROP TABLE IF EXISTS telemetry_stream CASCADE;
DROP TABLE IF EXISTS raw_audit_events CASCADE;
DROP TABLE IF EXISTS catalog_sync CASCADE;
DROP TABLE IF EXISTS billing_accounts CASCADE;
DROP TABLE IF EXISTS ops_orders CASCADE;
DROP TABLE IF EXISTS replication_heartbeat CASCADE;

-- 2. Таблица «пульса» кластера (Уроки 5.1–5.2)
CREATE TABLE replication_heartbeat (
    id         INT PRIMARY KEY,
    node_role  TEXT NOT NULL UNIQUE,
    beat_count INT NOT NULL DEFAULT 0 CHECK (beat_count >= 0),
    note       TEXT, -- NULL = без комментария
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 3. Таблица заказов (Уроки 5.1–5.4)
CREATE TABLE ops_orders (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer   TEXT NOT NULL,
    category   TEXT NOT NULL,
    amount     NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    status     TEXT NOT NULL DEFAULT 'new'
               CHECK (status IN ('new', 'paid', 'refunded', 'cancelled')),
    comment    TEXT, -- NULL = комментарий не указан
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 4. Таблица счетов биллинга (Уроки 5.2, 5.4)
CREATE TABLE billing_accounts (
    id         INT PRIMARY KEY,
    owner      TEXT NOT NULL UNIQUE,
    balance    NUMERIC(12, 2) NOT NULL CHECK (balance >= 0),
    tier       TEXT NOT NULL DEFAULT 'standard'
               CHECK (tier IN ('standard', 'vip')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 5. Каталог товаров для логической репликации с фильтром строк и колонок (Урок 5.3)
CREATE TABLE catalog_sync (
    id          INT PRIMARY KEY,
    sku         TEXT NOT NULL UNIQUE,
    title       TEXT NOT NULL,
    category    TEXT NOT NULL,
    price       NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    is_public   BOOLEAN NOT NULL DEFAULT true,
    secret_cost NUMERIC(10, 2) NOT NULL CHECK (secret_cost > 0) -- внутренняя себестоимость
);

-- 6. Журнал аудита СПЕЦИАЛЬНО БЕЗ PRIMARY KEY (ловушка REPLICA IDENTITY в Уроке 5.3)
CREATE TABLE raw_audit_events (
    event_ts TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor    TEXT NOT NULL,
    message  TEXT NOT NULL
);

-- 7. Поток телеметрии (5 000 строк для нагрузки WAL, измерения лага и сжатия pg_dump)
CREATE TABLE telemetry_stream (
    id           BIGSERIAL PRIMARY KEY,
    service_name TEXT NOT NULL,
    payload      TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

